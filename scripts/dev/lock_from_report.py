"""Build a hash-pinned lockfile from a `pip install --dry-run --report` JSON.

Usage: python scripts/dev/lock_from_report.py <report.json> <out.lock> [--table <out.md>]
"""
import json
import sys
from pathlib import Path


def main() -> int:
    args = sys.argv[1:]
    report_path, out_path = Path(args[0]), Path(args[1])
    table_path = Path(args[args.index("--table") + 1]) if "--table" in args else None

    report = json.loads(report_path.read_text(encoding="utf-8"))
    rows = []
    for item in report["install"]:
        meta = item["metadata"]
        name, version = meta["name"], meta["version"]
        info = item["download_info"]
        url = info["url"]
        sha = info.get("archive_info", {}).get("hashes", {}).get("sha256") or info.get(
            "archive_info", {}
        ).get("hash", "").removeprefix("sha256=")
        if not sha:
            print(f"ERROR: no sha256 for {name}", file=sys.stderr)
            return 1
        license_ = meta.get("license_expression") or (meta.get("license") or "").split("\n")[0][:40]
        direct = item.get("is_direct", False)
        rows.append((name.lower(), name, version, url, sha, license_ or "?", direct))

    rows.sort()
    lines = [
        "# Generated by scripts/dev/lock_from_report.py. Do not edit by hand.",
        "# Install: pip install --require-hashes --no-deps --only-binary=:all: -r <this file>",
    ]
    for _, name, version, url, sha, _, direct in rows:
        spec = f"{name} @ {url}" if direct else f"{name}=={version}"
        lines.append(f"{spec} \\\n    --hash=sha256:{sha}")
    out_path.write_text("\n".join(lines) + "\n", encoding="utf-8")

    if table_path:
        t = ["| Package | Version | License | SHA-256 | File |", "|---|---|---|---|---|"]
        for _, name, version, url, sha, lic, _ in rows:
            t.append(f"| {name} | {version} | {lic} | `{sha}` | {url.rsplit('/', 1)[-1]} |")
        table_path.write_text("\n".join(t) + "\n", encoding="utf-8")

    print(f"{len(rows)} packages locked -> {out_path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
